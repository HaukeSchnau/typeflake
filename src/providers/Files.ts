import * as Effect from "effect/Effect";
import * as FileSystem from "effect/FileSystem";
import * as Schema from "effect/Schema";
import * as Ast from "../Ast.ts";
import * as Nix from "../Nix.ts";
import * as Provider from "../Provider.ts";
import { property } from "../Typegen.ts";

/** Each imported file: its arguments and whether each may be left out, or null when it isn't a function. */
const Found = Schema.Record(
  Schema.String,
  Schema.NullOr(Schema.Record(Schema.String, Schema.Boolean)),
);

/** The `.nix` files modules import, relative to the root. */
const imported = (context: Provider.Context) =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem;
    const files = new Set<string>();
    for (const module of context.modules) {
      const source = yield* fs.readFileString(`${context.root}/${module}`);
      for (const [, specifier] of source.matchAll(/\bfrom\s+["'](\.\.?\/[^"']+\.nix)["']/g)) {
        if (specifier === undefined) continue;
        const url = new URL(specifier, `file:///${module}`);
        files.add(decodeURIComponent(url.pathname.slice(1)));
      }
    }
    return [...files].toSorted();
  });

const moduleArguments = new Set(["config", "options", "modulesPath"]);

/**
 * Declarations for the `.nix` files modules import, which TypeScript finds through
 * `allowArbitraryExtensions` and `rootDirs`. A package function's declaration lists its arguments,
 * required where it has no default and `pkgs` doesn't supply one, so `pkgs.callPackage` checks them.
 * Anything else is a module, which `imports` takes.
 */
export const provider = Provider.make({
  name: "files",
  schema: Found,
  nix: (context) =>
    imported(context).pipe(
      Effect.map((files) => {
        const paths = Ast.print(Nix.toExpr(files.map((file) => `${context.root}/${file}`)));
        return `configuration:
let
  pkgs = configuration.pkgs or { };
  describe = file: let value = import (/. + file); in if builtins.isFunction value then builtins.mapAttrs (name: optional: optional || pkgs ? \${name}) (builtins.functionArgs value) else null;
in
builtins.listToAttrs (map (file: { name = builtins.substring ${context.root.length + 1} (-1) file; value = describe file; }) ${paths.trim()})`;
      }),
      Effect.mapError((error) =>
        Provider.ProviderFailed.make({ provider: "files", reason: String(error) }),
      ),
    ),
  // An argument may be left out if any configuration's `pkgs` supplies it.
  combine: (left, right) =>
    Object.fromEntries(
      [...new Set([...Object.keys(left), ...Object.keys(right)])].map((file) => {
        const [a, b] = [left[file], right[file]];
        if (a === null || a === undefined || b === null || b === undefined)
          return [file, a ?? b ?? null];
        return [
          file,
          Object.fromEntries(
            [...new Set([...Object.keys(a), ...Object.keys(b)])].map((name) => [
              name,
              a[name] === true || b[name] === true,
            ]),
          ),
        ];
      }),
    ),
  provide: (found) =>
    Effect.succeed({
      ...Provider.nothing,
      files: Object.entries(found).map(([file, args]) => {
        const names = args === null ? [] : Object.keys(args);
        const isModule =
          args === null ||
          names.some((name) => moduleArguments.has(name)) ||
          names.every((name) => name === "lib" || name === "pkgs");
        const type = isModule
          ? "ModuleFile"
          : `PackageFile<{${Object.entries(args ?? {})
              .map(
                ([name, optional]) =>
                  ` readonly ${property(name)}${optional ? "?" : ""}: Argument;`,
              )
              .join("")} }>`;
        const imports = isModule ? "ModuleFile" : "Argument, PackageFile";
        return [
          `files/${file.replace(/\.nix$/, ".d.nix.ts")}`,
          `// Generated by Typeflake from ${file}. Do not edit.\nimport type { ${imports} } from "typeflake";\n\ndeclare const file: ${type};\nexport default file;\n`,
        ] as const;
      }),
    }),
});
