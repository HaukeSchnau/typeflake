export class ImportFailed extends Schema.TaggedError<
  ImportFailed,
  { readonly brand: unique symbol }
>()("ImportFailed", {
  file: Schema.String,
  message: Schema.String,
}) {}

/** A module's own effects failed while it rendered. */
export class RenderFailed extends Schema.TaggedError<
  RenderFailed,
  { readonly brand: unique symbol }
>()("RenderFailed", { file: Schema.String, message: Schema.String }) {}

export class NotAModule extends Schema.TaggedError<NotAModule, { readonly brand: unique symbol }>()(
  "NotAModule",
  {
    file: Schema.String,
  },
) {
  override get message() {
    return `${this.file} has no default export made with NixOS.module, Darwin.module or HomeManager.module`;
  }
}

/** Rendered files that differ from what their modules render now. */
export class Drift extends Schema.TaggedError<Drift, { readonly brand: unique symbol }>()("Drift", {
  files: Schema.Array(Schema.String),
}) {
  override get message() {
    return `out of date, run typeflake render: ${this.files.join(", ")}`;
  }
}

export class ProbeFailed extends Schema.TaggedError<
  ProbeFailed,
  { readonly brand: unique symbol }
>()("ProbeFailed", {
  configuration: Schema.String,
  exitCode: Schema.Int,
  stderr: Schema.String,
}) {
  override get message() {
    return `nix eval of ${this.configuration} exited with ${this.exitCode}:\n${this.stderr}`;
  }
}

/** What the CLI provides a module that renders with effects. */
export type Services = FileSystem.FileSystem | Path.Path | ChildProcessSpawner.ChildProcessSpawner;

/** A module file `x.nix.ts` renders `x.nix` next to it, so its relative paths stay valid. */
const suffix = ".nix.ts";
const skipped = /(^|\/)(node_modules|\.git|\.jj|\.typeflake|dist|result)(\/|$)/;

/** The module files under `root`, relative to it. */
export const moduleFiles = (root: string) =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem;
    const entries = yield* fs.readDirectory(root, { recursive: true });
    return entries.filter((entry) => entry.endsWith(suffix) && !skipped.test(entry)).toSorted();
  });

export interface Rendered {
  /** The `.nix` file, relative to the project root. */
  readonly file: string;
  readonly source: string;
}

/**
 * A module file's default export, rendered. Imported modules are only known at runtime, so this
 * trusts them to need no services beyond `Services`; Effect fails with the missing one's name if not.
 */
export const render = (root: string, file: string) =>
  Effect.gen(function* () {
    const path = yield* Path.Path;
    const url = yield* path.toFileUrl(path.resolve(root, file));
    const imported: unknown = yield* Effect.tryPromise({
      try: () => import(url.href),
      catch: (cause) => ImportFailed.make({ file, message: String(cause) }),
    });
    const module: unknown = Predicate.hasProperty(imported, "default")
      ? imported.default
      : undefined;
    if (!isModule(module)) return yield* NotAModule.make({ file });
    // SAFETY: only runtime knows what a dynamically imported module needs. The CLI provides
    // `Services`, Effect fails naming any other service, and its own errors become RenderFailed.
    // oxlint-disable-next-line typescript/no-unsafe-type-assertion, effecttsgo/any-unknown-in-error-context
    const source = yield* (module as Module<string, unknown, Services>).render.pipe(
      Effect.mapError((cause) => RenderFailed.make({ file, message: String(cause) })),
    );
    return {
      file: file.slice(0, -".ts".length),
      source: `# Generated by Typeflake from ${path.basename(file)}. Edit that file instead.\n${source}`,
    } satisfies Rendered;
  });

export const renderAll = (root: string) =>
  Effect.gen(function* () {
    const files = yield* moduleFiles(root);
    return yield* Effect.forEach(files, (file) => render(root, file), { concurrency: 8 });
  });

export const write = (root: string, rendered: ReadonlyArray<Rendered>) =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;
    yield* Effect.forEach(
      rendered,
      ({ file, source }) => fs.writeFileString(path.resolve(root, file), source),
      { discard: true },
    );
  });

/** Fails with the rendered files whose content on disk is out of date. */
export const check = (root: string, rendered: ReadonlyArray<Rendered>) =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;
    const stale = yield* Effect.filter(rendered, ({ file, source }) =>
      fs.readFileString(path.resolve(root, file)).pipe(
        Effect.map((current) => current !== source),
        Effect.orElseSucceed(() => true),
      ),
    );
    if (stale.length > 0) return yield* Drift.make({ files: stale.map(({ file }) => file) });
  });

/** The module class a flake output's configurations belong to. */
export const classOf = (configuration: string): string =>
  configuration.startsWith("darwinConfigurations.")
    ? "darwin"
    : configuration.startsWith("homeConfigurations.")
      ? "homeManager"
      : "nixos";

const probeFile = fileURLToPath(new URL("../src/probe.nix", import.meta.url));

const text = (stream: Stream.Stream<Uint8Array, PlatformError.PlatformError>) =>
  stream.pipe(Stream.decodeText(), Stream.mkString);

/** The JSON `probe.nix` makes of `<flake>#<configuration>.options`. */
export const probe = (flake: string, configuration: string) =>
  Effect.scoped(
    Effect.gen(function* () {
      const spawner = yield* ChildProcessSpawner.ChildProcessSpawner;
      const handle = yield* spawner.spawn(
        ChildProcess.make("nix", [
          "eval",
          "--impure",
          "--json",
          `${flake}#${configuration}.options`,
          "--apply",
          `import ${JSON.stringify(probeFile)} { class = ${JSON.stringify(classOf(configuration))}; }`,
        ]),
      );
      const [stdout, stderr, exitCode] = yield* Effect.all(
        [text(handle.stdout), text(handle.stderr), handle.exitCode],
        {
          concurrency: "unbounded",
        },
      );
      if (exitCode !== 0)
        return yield* ProbeFailed.make({ configuration, exitCode, stderr: stderr.slice(-4000) });
      return stdout;
    }),
  );

/**
 * Probes each configuration and writes its types to `.typeflake/<configuration>.ts`. A module class
 * registers with the first configuration that has it, since `Register` holds one type per class.
 */
export const types = (root: string, flake: string, configurations: ReadonlyArray<string>) =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;
    const directory = path.resolve(root, ".typeflake");
    yield* fs.makeDirectory(directory, { recursive: true });
    let registered: ReadonlySet<string> = new Set();
    for (const configuration of configurations) {
      const tree = yield* decodeOptionTree(yield* probe(flake, configuration));
      const generated = generate(tree, {
        rootClass: classOf(configuration),
        importFrom: "typeflake",
        registered,
      });
      registered = new Set([...registered, ...generated.registered]);
      yield* fs.writeFileString(path.join(directory, `${configuration}.ts`), generated.source);
    }
    return [...registered];
  });
